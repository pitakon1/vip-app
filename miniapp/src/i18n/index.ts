function readStorage(): AppLang {
  try {
    const v = Taro.getStorageSync(LANG_STORAGE_KEY) as string | null | undefined
    if (v === 'en' || v === 'th' || v === 'zh') return v
  } catch {
    /* ignore */
  }
  return 'zh'
}

export const useI18n = create<I18nState>((set, get) => ({
  lang: readStorage(),
  setLang: (lang) => {
    set({ lang })
    try {
      Taro.setStorageSync(LANG_STORAGE_KEY, lang)
    } catch {
      /* ignore */
    }
  },
  t: (key, params) => {
    let text = messages[get().lang][key] ?? messages.zh[key] ?? key
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.split(`{${name}}`).join(String(value))
      }
    }
    return text
  },
}))